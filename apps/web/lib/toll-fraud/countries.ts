export type ResolvableCountry = (typeof RESOLVABLE_COUNTRIES)[number];

const RESOLVABLE_SET: ReadonlySet<string> = new Set<string>(RESOLVABLE_COUNTRIES);

export function isResolvableCountry(value: string): boolean {
	return RESOLVABLE_SET.has(value);
}

/**
 * "DE" as "Germany (DE)", or just the code when the runtime has no name for it.
 *
 * `Intl.DisplayNames` is the browser's own table and is not the same table as the one above —
 * `XK` in particular has no ISO name — so the code is always kept in the label. A chip reading
 * only "Germany" would also make a list impossible to check against the API's error messages,
 * which name codes.
 */
export function countryLabel(code: string, displayNames: Intl.DisplayNames | null): string {
	if (displayNames === null) {
		return code;
	}
	let name: string | undefined;
	try {
		name = displayNames.of(code);
	} catch {
		name = undefined;
	}
	return name === undefined || name === code ? code : `${name} (${code})`;
}

/** `null` when this runtime has no region display names, which is a supported outcome above. */
export function regionDisplayNames(): Intl.DisplayNames | null {
	try {
		return new Intl.DisplayNames(undefined, { type: "region" });
	} catch {
		return null;
	}
}
